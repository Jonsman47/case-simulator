import { expect, test } from '@playwright/test'

test('optional Work walkthrough highlights real controls, survives reload, and yields to a minigame', async ({ page }) => {
  await page.goto('/work?guide=1')
  const skipBeginner = page.getByRole('button', { name: 'Skip beginner tutorial' })
  if (await skipBeginner.isVisible().catch(() => false)) await skipBeginner.click()
  const guide = page.getByTestId('feature-walkthrough')
  await expect(guide).toContainText('Choose a job')
  const target = await page.locator('[data-guide-target="work-job-card"]').first().boundingBox()
  const spotlight = await page.getByTestId('walkthrough-spotlight').boundingBox()
  expect(target).not.toBeNull()
  expect(spotlight).not.toBeNull()
  expect(Math.abs(spotlight!.x - target!.x)).toBeLessThan(6)
  await guide.getByRole('button', { name: 'Next' }).click()
  await expect(guide).toContainText('Check pay and cooldown')
  await page.reload()
  await expect(guide).toContainText('Check pay and cooldown')
  await guide.getByRole('button', { name: 'Next' }).click()
  await expect(guide).toContainText('Play at your pace')
  await page.getByRole('button', { name: 'Play Precision Strike' }).click()
  await expect(page.getByRole('dialog', { name: 'Precision Strike minigame' })).toBeVisible()
  await expect(guide).not.toBeVisible()
  await page.getByRole('button', { name: 'Close Precision Strike' }).click()
  await expect(guide).toBeVisible()
  await guide.getByRole('button', { name: 'Skip guide' }).click()
  await expect(guide).not.toBeVisible()
})

test('the optional guide stays within a narrow mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/work?guide=1')
  const skipBeginner = page.getByRole('button', { name: 'Skip beginner tutorial' })
  if (await skipBeginner.isVisible().catch(() => false)) await skipBeginner.click()
  const guide = page.getByTestId('feature-walkthrough')
  await expect(guide).toBeVisible()
  const box = await guide.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(568)
})
