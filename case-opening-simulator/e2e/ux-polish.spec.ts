import { expect, test } from '@playwright/test'

const saveKey = 'case-opening-simulator:game-state'

test('opening feedback stays behind the reveal and individual toasts preserve rewards', async ({ page }) => {
  await page.goto('/')
  const skipGuide = page.getByRole('button', { name: 'Skip beginner tutorial' })
  await expect(skipGuide).toBeVisible()
  await skipGuide.click()
  await page.waitForFunction((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.ui?.onboarding?.isDismissed === true, saveKey)
  await page.goto('/cases')
  const before = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state, saveKey)
  await page.getByRole('button', { name: 'Open 10' }).click()
  const reveal = page.getByRole('dialog', { name: 'Case opening animation' })
  await expect(reveal).toBeVisible()
  await expect(page.getByTestId('toast-stack')).toBeHidden()
  await reveal.getByRole('button', { name: 'Skip opening animation' }).click()
  const summary = page.getByRole('dialog', { name: 'Case opening batch summary' })
  await expect(summary).toBeVisible()
  await expect(page.getByTestId('toast-stack')).toBeHidden()
  await summary.getByRole('button', { name: 'Close opening summary' }).click()
  await page.waitForFunction(({ key, count }) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.statistics?.casesOpened >= count + 10, { key: saveKey, count: before.statistics.casesOpened })
  const toasts = page.getByTestId('toast-stack').locator('[data-toast-id]')
  await expect(toasts.first()).toBeVisible()
  await expect(toasts).toHaveCount(3)
  const firstId = await toasts.first().getAttribute('data-toast-id')
  const secondId = await toasts.nth(1).getAttribute('data-toast-id')
  const thirdId = await toasts.nth(2).getAttribute('data-toast-id')
  await toasts.nth(1).getByRole('button', { name: /Dismiss .* notification/ }).click()
  await expect(page.locator(`[data-toast-id="${secondId}"]`)).toBeHidden()
  await expect(page.locator(`[data-toast-id="${firstId}"]`)).toBeVisible()
  await expect(page.locator(`[data-toast-id="${thirdId}"]`)).toBeVisible()
  await expect(toasts).toHaveCount(3)
  const after = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state, saveKey)
  expect(after.inventory.length - before.inventory.length).toBeGreaterThan(0)
  expect(after.money).toBeLessThan(before.money)
  await page.getByRole('link', { name: 'Inventory', exact: true }).click()
  await expect(page.locator('[data-recent-acquisition="true"]').first()).toBeVisible()
  await page.goto('/progress?tab=achievements')
  const claimAll = page.getByRole('button', { name: /Claim All/ })
  await expect(claimAll).toBeVisible()
  const beforeClaim = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state, saveKey)
  await claimAll.click()
  await page.waitForFunction(({ key, count }) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.achievements?.filter((entry: { isClaimed: boolean }) => entry.isClaimed).length > count, { key: saveKey, count: beforeClaim.achievements.filter((entry: { isClaimed: boolean }) => entry.isClaimed).length })
  const afterClaim = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state, saveKey)
  expect(afterClaim.money).toBeGreaterThan(beforeClaim.money)
  await expect(claimAll).toBeDisabled()
  await expect(page.getByText(/Reward claimed/).first()).toBeVisible()
})

test('mobile notifications fit with Large Text, Light Mode and reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Skip beginner tutorial' }).click()
  await page.waitForFunction((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.ui?.onboarding?.isDismissed === true, saveKey)
  const save = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}'), saveKey)
  save.state.settings = { ...save.state.settings, theme: 'light', largeText: true, simplifiedAnimations: true }
  await page.addInitScript(({ key, value }) => {
    if (sessionStorage.getItem('polish-settings-seeded')) return
    localStorage.setItem(key, JSON.stringify(value))
    sessionStorage.setItem('polish-settings-seeded', '1')
  }, { key: saveKey, value: save })
  await page.reload()
  await page.goto('/cases')
  await page.getByRole('button', { name: 'Open 10' }).click()
  await expect(page.getByRole('dialog', { name: 'Case opening batch summary' })).toBeVisible()
  await page.getByRole('button', { name: 'Close opening summary' }).click()
  const first = page.getByTestId('toast-stack').locator('[data-toast-id]').first()
  await expect(first).toBeVisible()
  const box = await first.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  expect(box!.y + box!.height).toBeLessThanOrEqual(568)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  const dismissedId = await first.getAttribute('data-toast-id')
  await first.getByRole('button', { name: /Dismiss .* notification/ }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator(`[data-toast-id="${dismissedId}"]`)).toBeHidden()
})
