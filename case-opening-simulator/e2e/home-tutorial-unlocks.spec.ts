import { expect, test } from '@playwright/test'

const saveKey = 'case-opening-simulator:game-state'

test('fresh player follows the real first-opening tutorial and returns to Home', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.goto('/')
  const guide = page.getByTestId('onboarding-tutorial')
  await expect(guide).toContainText('This is a CS2 case-opening simulator')
  await guide.getByRole('button', { name: 'Continue' }).click()
  await expect(guide).toContainText('Your cash')
  await guide.getByRole('button', { name: 'Continue' }).click()
  await expect(guide).toContainText('Find a case')
  await page.locator('[data-onboarding-target="nav-cases"]:visible').first().click()
  await expect(guide).toContainText('Choose an affordable case')
  await page.locator('[data-onboarding-target="starter-case"]').click()
  await expect(guide).toContainText('Open one case')
  await page.waitForFunction((key) => Boolean(JSON.parse(localStorage.getItem(key) ?? '{}').state?.statistics), saveKey)
  const before = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state.statistics.casesOpened, saveKey)
  await page.getByRole('button', { name: 'Open 1', exact: true }).click()
  await expect(guide).toContainText('Watch the result')
  const opening = page.getByRole('dialog', { name: 'Case opening animation' })
  await expect(opening).toBeVisible()
  await opening.getByRole('button', { name: 'Skip opening animation' }).click()
  await expect(guide).toContainText('Your new skin', { timeout: 15_000 })
  await page.waitForFunction(({ key, expected }) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.statistics?.casesOpened === expected, { key: saveKey, expected: before + 1 })
  const after = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state.statistics.casesOpened, saveKey)
  expect(after).toBe(before + 1)
  await guide.getByRole('button', { name: 'Continue' }).click()
  const close = opening.getByRole('button', { name: 'Skip opening animation' })
  if (await close.isVisible().catch(() => false)) await close.click().catch(() => undefined)
  await expect(opening).toBeHidden({ timeout: 15_000 })
  await page.locator('[data-onboarding-target="nav-inventory"]:visible').first().click()
  await expect(guide).toContainText('Inspect your skin')
  await page.locator('[data-onboarding-target="acquired-item"]').click()
  await expect(guide).toContainText('Quests give you goals')
  await guide.getByRole('button', { name: 'Go to quests' }).click()
  await expect(guide).toContainText('Earn cash in Work')
  await page.locator('[data-onboarding-target="nav-work"]:visible').first().click()
  await expect(guide).toContainText('You are ready')
  await guide.getByRole('button', { name: 'Go to Home' }).click()
  await guide.getByRole('button', { name: 'Finish' }).click()
  await expect(guide).toBeHidden()
  await expect(page.getByRole('heading', { name: 'Continue Opening' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Current goals' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Recent activity' })).toBeVisible()
})

