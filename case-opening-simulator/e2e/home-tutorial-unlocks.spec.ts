test('real openings permanently unlock early features and compatible Trade-Ups', async ({ page }) => {
  test.setTimeout(180_000)
  await page.goto('/')
  await page.getByRole('button', { name: 'Skip beginner tutorial' }).click()
  await expect(page.getByRole('heading', { name: 'Next unlock' })).toBeVisible()
  await page.goto('/trade-ups')
  await expect(page.getByText('Feature locked')).toBeVisible()
  await page.goto('/work')
  await page.getByRole('button', { name: 'Play Sort Boxes' }).click()
  await page.getByRole('button', { name: 'Start Sort Boxes' }).click()
  for (const color of ['Red', 'Blue', 'Green', 'Yellow']) {
    await page.getByRole('button', { name: `${color} box` }).click()
    await page.getByRole('button', { name: `${color} container` }).click()
  }
  await expect(page.getByText('Earned $20.00')).toBeVisible()
  await page.waitForFunction((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.statistics?.workJobsCompleted >= 1, saveKey)
  await page.getByRole('button', { name: 'Close Sort Boxes' }).click()
  await page.goto('/cases?case=crate-4904')
  for (let round = 0; round < 6; round += 1) {
    await page.getByRole('button', { name: 'Open 10', exact: true }).click()
    const opening = page.getByRole('dialog', { name: 'Case opening animation' })
    await opening.getByRole('button', { name: 'Skip opening animation' }).click()
    await page.waitForFunction(() => {
      const dialog = document.querySelector('[role="dialog"][aria-label="Case opening animation"]')
      const control = dialog?.querySelector('button[aria-label="Skip opening animation"]')
      return !dialog || control?.textContent?.includes('Close')
    })
    if (await opening.isVisible().catch(() => false)) await opening.getByRole('button', { name: 'Skip opening animation' }).click().catch(() => undefined)
    await expect(opening).toBeHidden({ timeout: 15_000 })
    const summary = page.getByRole('dialog', { name: 'Case opening batch summary' })
    if (await summary.isVisible().catch(() => false)) await summary.getByRole('button', { name: 'Close opening summary' }).click()
    while (await page.getByRole('button', { name: 'Maybe later' }).isVisible().catch(() => false)) await page.getByRole('button', { name: 'Maybe later' }).click()
    await page.waitForFunction(({ key, count }) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.statistics?.casesOpened >= count, { key: saveKey, count: (round + 1) * 10 })
    const unlocked = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.ui?.featureUnlocks?.unlockedIds ?? [], saveKey)
    if (unlocked.includes('trade-ups')) break
  }
  await page.waitForFunction((key) => JSON.parse(localStorage.getItem(key) ?? '{}').state?.ui?.featureUnlocks?.unlockedIds?.includes('trade-ups'), saveKey)
  const save = await page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}'), saveKey)
  expect(save.state.ui.featureUnlocks.unlockedIds).toEqual(expect.arrayContaining(['collection-book', 'quests', 'trade-ups']))
  await page.goto('/trade-ups')
  await expect(page.getByTestId('trade-up-workbench')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('trade-up-workbench')).toBeVisible()
})

test('v41 returning player keeps old access without a forced welcome', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction((key) => Boolean(JSON.parse(localStorage.getItem(key) ?? '{}').state), saveKey)
  const legacy = await page.evaluate((key) => {
    const save = JSON.parse(localStorage.getItem(key) ?? '{}')
    save.version = 41
    save.state.ui.onboarding = { ...save.state.ui.onboarding, version: 1, isDismissed: true }
    delete save.state.ui.featureUnlocks
    return JSON.stringify(save)
  }, saveKey)
  await page.addInitScript((value) => { if (!sessionStorage.getItem('legacy-loaded')) { localStorage.setItem('case-opening-simulator:game-state', value); sessionStorage.setItem('legacy-loaded', '1') } }, legacy)
  await page.reload()
  await expect(page.getByTestId('onboarding-tutorial')).toBeHidden()
  await page.goto('/trade-ups')
  await expect(page.getByTestId('trade-up-workbench')).toBeVisible()
  await page.goto('/business')
  await expect(page.getByRole('heading', { name: 'Business', exact: true })).toBeVisible()
})
