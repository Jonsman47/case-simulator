import fs from 'node:fs'
import path from 'node:path'
import BlueGemCalculator from 'csgo-blue-gem-calculator'
import { FadeCalculator } from 'csgo-fade-percentage-calculator'

const outputPath = path.resolve(process.cwd(), 'src/data/generated/patternPercentages.generated.ts')
const blueGemCalculator = new BlueGemCalculator()

function roundPercentage(value) {
  return typeof value === 'number' && Number.isFinite(value) ? Math.round(value * 100) / 100 : null
}

function createBlueRows(finish) {
  return Object.fromEntries(blueGemCalculator.getSupportedItems(finish).map((weapon) => [
    `${finish}|${weapon}`,
    Array.from({ length: 1001 }, (_, pattern) => {
      const percentages = blueGemCalculator.getPercentages(finish, weapon, pattern)
      return roundPercentage(percentages.top?.blue ?? percentages.playside?.blue)
    }),
  ]))
}

const blueRows = {
  ...createBlueRows('Case Hardened'),
  ...createBlueRows('Heat Treated'),
}
const fadeRows = Object.fromEntries(FadeCalculator.getSupportedWeapons().map((weapon) => [
  weapon,
  Array.from({ length: 1001 }, (_, pattern) => roundPercentage(FadeCalculator.getFadePercentage(weapon, pattern).percentage)),
]))

const source = `// Generated by scripts/generatePatternLookup.mjs. Do not hand-edit.\n` +
  `export const BLUE_PATTERN_PERCENTAGES: Record<string, readonly (number | null)[]> = ${JSON.stringify(blueRows)}\n\n` +
  `export const FADE_PATTERN_PERCENTAGES: Record<string, readonly (number | null)[]> = ${JSON.stringify(fadeRows)}\n`

fs.writeFileSync(outputPath, source)
console.log(`Wrote ${path.relative(process.cwd(), outputPath)} (${Buffer.byteLength(source).toLocaleString()} bytes).`)
